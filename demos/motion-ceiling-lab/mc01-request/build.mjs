#!/usr/bin/env node
/* Build data.js from the lab fixture and editable.json, refusing inputs the scene would have to guess.
 *
 *   node build.mjs                 → data.js for the main piece
 *   node build.mjs <variant>       → variants/<variant>/ (data.js + index.html) from variants/<variant>.json
 *   node build.mjs --all           → the main piece and every variant
 *
 * A variant file is { describe, expect, refuse_with?, fixture?: [events], patch?: { …deep-merged into editable.json } }.
 * Objects merge key by key, arrays replace; an object carrying "$replace": true replaces the whole object.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const Model = createRequire(import.meta.url)('./model.js');
const read = (p) => JSON.parse(readFileSync(join(here, p), 'utf8'));

function merge(base, patch) {
  if (Array.isArray(patch) || patch === null || typeof patch !== 'object') return patch;
  if (patch.$replace) { const { $replace, ...rest } = patch; return rest; }
  const out = { ...base };
  for (const k of Object.keys(patch)) out[k] = Object.hasOwn(base ?? {}, k) ? merge(base[k], patch[k]) : patch[k];
  return out;
}

function assemble(variant) {
  let editable = read('editable.json');
  const lab = read(editable.fixture.file);
  let events = lab[editable.fixture.key];
  let provenance = { ...lab.provenance, file: editable.fixture.file, key: editable.fixture.key, schema_version: lab.schema_version };
  if (variant) {
    const v = read(`variants/${variant}.json`);
    if (v.patch) editable = merge(editable, v.patch);
    if (v.fixture) { events = v.fixture; provenance = { ...provenance, replaced_by: `variants/${variant}.json`, kind: 'synthetic' }; }
    editable.variant = { name: variant, describe: v.describe, expect: v.expect };
  }
  editable.tag = `SYNTHETIC · ${editable.id} ${editable.revision}${variant ? ` · 变体 ${variant}` : ''} · ${editable.tagNote}`;
  if (variant) editable.revision = `${editable.revision}+${variant}`;
  const data = { ...editable, fixture: { events, provenance } };
  const model = Model.build(data); // throws on anything it would have to guess
  return { data, model };
}

function emit(variant) {
  const { data, model } = assemble(variant);
  const js = `/* generated by build.mjs from editable.json and ${data.fixture.provenance.replaced_by || data.fixture.provenance.file}; edit those, not this file */\nwindow.MC01_DATA = ${JSON.stringify(data, null, 1)};\n`;
  if (!variant) {
    writeFileSync(join(here, 'data.js'), js);
  } else {
    const dir = join(here, 'variants', variant);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'data.js'), js);
    writeFileSync(join(dir, 'index.html'), readFileSync(join(here, 'index.html'), 'utf8')
      .replace(/(src|href)="(?!https?:|data\.js)([^"#]+)"/g, (_, a, p) => `${a}="../../${p}"`));
    writeFileSync(join(dir, 'README.md'), `# 变体 ${variant}\n\n由 \`node build.mjs ${variant}\` 从 [${variant}.json](../${variant}.json) 生成，不手改。${data.variant.describe}\n\n预期：${data.variant.expect}\n\n打开 [index.html](index.html) 运行；代码与主片共用，只有 \`data.js\` 不同。检查结果见 [验收回执](../../acceptance.md)。返回 [变体说明](../README.md)。\n`);
  }
  return `${variant || 'main'}: ${model.reqs.length} 条请求，${model.events.length} 条事件，片长 ${model.duration} 秒`;
}

const arg = process.argv[2];
try {
  if (arg === '--all') {
    console.log(emit(null));
    for (const f of readdirSync(join(here, 'variants')).filter((f) => f.endsWith('.json')).sort()) {
      const name = f.replace(/\.json$/, '');
      try { console.log(emit(name)); } catch (e) { console.log(`${name}: ${e.message}`); }
    }
  } else console.log(emit(arg || null));
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
